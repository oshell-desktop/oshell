import AppKit

/// Real Spaces/app activation, synthetic input into a disposable blank terminal.
final class FullscreenActivationTest {
    private static var retained: FullscreenActivationTest?
    private let workspace: WorkspaceController
    private var peer: Process?, heartbeat: Timer?
    private var checks = [String: Bool](), metrics = [String: Double]()
    private var finished = false, lastBeat = ProcessInfo.processInfo.systemUptime
    private var delivered = 0, round = 0
    private var roundStarted = ProcessInfo.processInfo.systemUptime
    private var window: NSWindow { workspace.window! }
    private var pane: TerminalPane { workspace.selectedTab!.activePane }
    init(_ workspace: WorkspaceController) { self.workspace = workspace }
    static func run(_ workspace: WorkspaceController) {
        let test = FullscreenActivationTest(workspace); retained = test
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) { test.start() }
    }
    private func wait(_ name: String, _ condition: @escaping () -> Bool, _ action: @escaping () -> Void) {
        let deadline = ProcessInfo.processInfo.systemUptime + 15
        func poll() {
            guard !self.finished else { return }
            if condition() { self.checks[name] = true; action() }
            else if ProcessInfo.processInfo.systemUptime > deadline { self.checks[name] = false; self.finish() }
            else { DispatchQueue.main.asyncAfter(deadline: .now() + 0.05, execute: poll) }
        }
        poll()
    }
    private func start() {
        workspace.configuration.preferences.metal = ProcessInfo.processInfo.environment["OSHELL_ACTIVATION_METAL"] == "1"
        for _ in 0..<24 { workspace.newBlankTab() }
        workspace.newLocal()
        // Count only the synthetic character, not selection/cursor reports
        // generated by the mouse click or unrelated physical keyboard input.
        pane.onUserInput = { [weak self] _, bytes in
            if bytes == [97] { self?.delivered += 1 }
            return false
        }
        wait("localPTYRunning", { self.pane.terminal.process.running }) { [self] in
            pane.sendManaged(Array("stty -icanon -echo; printf '\\nACTIVATION_READY\\n'; exec /bin/cat\r".utf8))
            wait("echoFixtureReady", { String(decoding: self.pane.terminal.getTerminal().getBufferAsData(), as: UTF8.self).contains("\nACTIVATION_READY\n") }) { self.startFullscreen() }
        }
    }
    private func startFullscreen() {
        workspace.requestFocusFullscreen(true)
        wait("nativeFullscreen", { self.window.styleMask.contains(.fullScreen) && !self.workspace.fullscreenTransitionInProgress }) { [self] in
            guard let path = ProcessInfo.processInfo.environment["OSHELL_ACTIVATION_PEER"] else { checks["peerConfigured"] = false; finish(); return }
            let task = Process(); task.executableURL = URL(fileURLWithPath: path)
            task.standardOutput = FileHandle.nullDevice; task.standardError = FileHandle.nullDevice
            do { try task.run(); peer = task } catch { checks["peerLaunched"] = false; finish(); return }
            wait("otherAppActive", { !NSApp.isActive }) { self.returnToTerminal() }
        }
    }
    private func returnToTerminal() {
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) { [self] in
            let began = ProcessInfo.processInfo.systemUptime
            lastBeat = began
            heartbeat = Timer(timeInterval: 0.02, repeats: true) { [weak self] _ in
                guard let self else { return }
                let now = ProcessInfo.processInfo.systemUptime
                self.metrics["maximumMainRunLoopGapMilliseconds"] = max(self.metrics["maximumMainRunLoopGapMilliseconds"] ?? 0, (now - self.lastBeat) * 1000)
                self.lastBeat = now
            }
            RunLoop.main.add(heartbeat!, forMode: .common)
            NSApp.activate(ignoringOtherApps: true); window.makeKeyAndOrderFront(nil)
            metrics["activateCallMilliseconds-\(round)"] = (ProcessInfo.processInfo.systemUptime - began) * 1000
            wait("returnedActive-\(round)", { NSApp.isActive && self.window.isKeyWindow }) { [self] in
                metrics["returnToActiveMilliseconds-\(round)"] = (ProcessInfo.processInfo.systemUptime - began) * 1000
                let location = pane.terminal.convert(NSPoint(x: 40, y: 40), to: nil)
                let clickStart = ProcessInfo.processInfo.systemUptime
                for type in [NSEvent.EventType.leftMouseDown, .leftMouseUp] {
                    let event = NSEvent.mouseEvent(with: type, location: location, modifierFlags: [], timestamp: ProcessInfo.processInfo.systemUptime, windowNumber: window.windowNumber, context: nil, eventNumber: 1, clickCount: 1, pressure: 1)!
                    window.sendEvent(event)
                }
                metrics["mouseDispatchMilliseconds-\(round)"] = (ProcessInfo.processInfo.systemUptime - clickStart) * 1000
                roundStarted = ProcessInfo.processInfo.systemUptime
                for index in 0..<20 {
                    let start = ProcessInfo.processInfo.systemUptime
                    let event = NSEvent.keyEvent(with: .keyDown, location: .zero, modifierFlags: [], timestamp: start, windowNumber: window.windowNumber, context: nil, characters: "a", charactersIgnoringModifiers: "a", isARepeat: false, keyCode: 0)!
                    window.sendEvent(event)
                    let elapsed = (ProcessInfo.processInfo.systemUptime - start) * 1000
                    if index == 0 { metrics["firstKeyMilliseconds-\(round)"] = elapsed }
                    metrics["maximumKeyMilliseconds"] = max(metrics["maximumKeyMilliseconds"] ?? 0, elapsed)
                }
                wait("ptyEchoReceived-\(round)", { self.pane.terminal.getTerminal().getCursorLineText().contains(String(repeating: "a", count: (self.round + 1) * 20)) }) { [self] in
                    metrics["inputToParsedEchoMilliseconds-\(round)"] = (ProcessInfo.processInfo.systemUptime - roundStarted) * 1000
                    wait("echoFrameDrawn-\(round)", {
                        if self.pane.terminal.isUsingMetalRenderer {
                            return self.pane.terminal.metalRendererStatus.lastFramePresentedAt.map { $0.timeIntervalSinceNow > -(ProcessInfo.processInfo.systemUptime - self.roundStarted) } == true
                        }
                        return self.pane.terminal.lastDrawForTesting >= self.roundStarted
                    }) { self.finishRound() }
                }
            }
        }
    }
    private func finishRound() {
        metrics["inputToDisplayMilliseconds-\(round)"] = (ProcessInfo.processInfo.systemUptime - roundStarted) * 1000
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.7) { [self] in
                    heartbeat?.invalidate(); heartbeat = nil
                    metrics["syntheticKeysDelivered-\(round)"] = Double(delivered)
                    checks["keysDelivered-\(round)"] = delivered == (round + 1) * 20
                    checks["focusPreserved-\(round)"] = window.firstResponder === pane.terminal
                    if round == 2 { finish(); return }
                    round += 1
                    guard let peer, let app = NSRunningApplication(processIdentifier: peer.processIdentifier) else { checks["peerAlive"] = false; finish(); return }
                    app.activate(options: [.activateIgnoringOtherApps])
                    wait("otherAppActive-\(round)", { !NSApp.isActive }) { self.returnToTerminal() }
        }
    }
    private func finish() {
        guard !finished else { return }; finished = true
        heartbeat?.invalidate(); if peer?.isRunning == true { peer?.terminate() }
        if checks["keysDelivered-2"] == true {
            checks["noMultiSecondKeyDispatch"] = (metrics["maximumKeyMilliseconds"] ?? .infinity) < 1000
            checks["noMultiSecondMainThreadPause"] = (metrics["maximumMainRunLoopGapMilliseconds"] ?? .infinity) < 1000
        }
        let state: [String: Bool] = ["appActive": NSApp.isActive, "windowKey": window.isKeyWindow, "nativeFullscreen": window.styleMask.contains(.fullScreen), "transition": workspace.fullscreenTransitionInProgress]
        let report: [String: Any] = ["passed": checks.values.allSatisfy { $0 }, "checks": checks, "metrics": metrics, "state": state, "metalActive": pane.terminal.isUsingMetalRenderer, "scope": "Requires unlocked desktop. Native fullscreen, separate AppKit app, synthetic ASCII input, real local PTY echo and display; no SSH or human IME composition"]
        if let path = ProcessInfo.processInfo.environment["OSHELL_FULLSCREEN_ACTIVATION_OUTPUT"], let data = try? JSONSerialization.data(withJSONObject: report, options: [.prettyPrinted, .sortedKeys]) { try? data.write(to: URL(fileURLWithPath: path)) }
        workspace.shutdown(); NSApp.terminate(nil)
    }
}
